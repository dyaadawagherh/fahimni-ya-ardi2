for (const m of MISSIONS) {
  m.suggestions.forEach((list, i) => {
    if (DEMO[m.id].rounds[i].length !== list.length) {
      throw new Error(`demo replies mismatch: ${m.id} round ${i + 1}`);
    }
  });
}
