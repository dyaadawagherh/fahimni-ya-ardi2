const tokens = (s) =>
  s
    .replace(/[«»"'“”‘’؟?!.,،…:؛()]/g, ' ')
    .split(/\s+/)
    .filter((w) => w.length >= 3);

// يطابق سؤال اللاعب مع أقرب سؤال مقترح في نفس الجولة. إذا لم يشبه أياً منها نرجع أول رد ونعلّمه بـ canned.
function pickReply(mission, round, question) {
  const suggestions = mission.suggestions[round - 1];
  const replies = DEMO[mission.id].rounds[round - 1];
  const exact = suggestions.indexOf(question);
  if (exact !== -1) return { ...replies[exact], canned: false };

  const asked = new Set(tokens(question));
  let best = 0;
  let bestScore = 0;
  suggestions.forEach((s, i) => {
    const score = tokens(s).filter((w) => asked.has(w)).length;
    if (score > bestScore) {
      best = i;
      bestScore = score;
    }
  });
  return { ...replies[best], canned: bestScore < 2 };
}

export function demoTurn(mission, round, alienTexts, jordanianTexts) {
  const { canned, ...turn } = pickReply(mission, round, alienTexts[alienTexts.length - 1]);
  const out = { ...turn, canned };
  if (round >= ROUNDS) {
    out.report = shapeReport(
      { ...DEMO[mission.id].report, bestExplanation: '', funniestReaction: '' },
      { jordanianTexts: [...jordanianTexts, turn.reply], alienTexts },
    );
  }
  return out;
}

