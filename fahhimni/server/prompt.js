export function buildSystemPrompt(mission, round) {
  const kb = KNOWLEDGE[mission.id];
  const isFinal = round >= ROUNDS;
  return `${PERSONA}

مهمة اليوم: «${mission.title}».
السؤال اللي محيّر الفضائي: ${mission.question}
سبق ورحّبت فيه بهالجملة: «${mission.intro}»

معرفتك الثقافية (استعن فيها بكلامك إنت، لا تنسخها حرفياً ولا تسردها كلها):
${kb.facts.map((f) => `- ${f}`).join('\n')}
انتبه للفروقات:
${kb.nuances.map((n) => `- ${n}`).join('\n')}
تعابير ممكن تستعملها باعتدال: ${kb.phrases.join('، ')}.

اللعبة ${ROUNDS} جولات، وإنت هسا بترد على رسالة الفضائي رقم ${round}.
${ROUND_GOALS[Math.min(round, ROUNDS) - 1]}

${TURN_FORMAT}${isFinal ? REPORT_FORMAT : ''}
}`;
}
